def load_show_json_map(json_path):
    """
    Parses show_data.json into an ordered map of scene_idx -> {actor: character_name(s)}.
    Supports both:
      - Standard scene format: "scene_1": [ {"character_name": ..., "associated_actor": ...}, ... ]
      - Quick-scene object format: "scene_3": { "quick_scene": true, "cast": [ ... ] }
    """
    if not json_path or not os.path.exists(json_path):
        return None

    with open(json_path, mode="r", encoding="utf-8") as f:
        show_json = json.load(f)

    act_keys = sorted(
        show_json.keys(),
        key=lambda x: int(x.split("_")[-1]) if x.split("_")[-1].isdigit() else str(x)
    )

    scene_char_map = {}
    s_global_idx = 0

    for act_key in act_keys:
        scene_dict = show_json[act_key]
        scene_keys = sorted(
            scene_dict.keys(),
            key=lambda x: int(x.split("_")[-1]) if x.split("_")[-1].isdigit() else str(x)
        )
        for scene_key in scene_keys:
            raw_scene = scene_dict[scene_key]

            # Extract cast list whether the scene is a dict with "cast" or a direct list
            if isinstance(raw_scene, dict):
                cast = raw_scene.get("cast", [])
            elif isinstance(raw_scene, list):
                cast = raw_scene
            else:
                cast = []

            char_lookup = defaultdict(list)
            for entry in cast:
                actor = entry.get("associated_actor", "").strip()
                char = entry.get("character_name", "").strip()
                if actor and char and char not in char_lookup[actor]:
                    char_lookup[actor].append(char)

            scene_char_map[s_global_idx] = {
                actor: " / ".join(chars) for actor, chars in char_lookup.items()
            }
            s_global_idx += 1

    return scene_char_map


def parse_tracking_csv(csv_path, scene_char_map=None):
    """
    Parses mic_tracking_sheet.csv and builds a full timeline for every mic pack,
    pre-filling early scenes with the initial wearer's character so pre-rigged
    packs never say 'Idle' at the top of the show.
    """
    with open(csv_path, mode="r", encoding="utf-8") as f:
        reader = list(csv.reader(f))

    header_idx = None
    scenes = []
    mode = None

    for idx, row in enumerate(reader):
        if not row:
            continue
        if len(row) >= 4 and row[0].strip() == "Mic #" and "Actor" in row[1]:
            header_idx = idx
            scenes = [col.strip() for col in row[3:] if col.strip()]
            mode = "STINT_SPLIT"
            break
        elif len(row) >= 3 and row[0].strip() == "Mic #" and "Channel Type" in row[1]:
            header_idx = idx
            scenes = [col.strip() for col in row[2:] if col.strip()]
            mode = "MATRIX"
            break

    if header_idx is None:
        raise ValueError("Could not locate the 'Mic #' header row in the CSV file.")

    num_scenes = len(scenes)
    raw_stints = defaultdict(list)
    all_mics = set()

    if mode == "STINT_SPLIT":
        for row in reader[header_idx + 1:]:
            if not row or not row[0].strip().startswith("Mic "):
                if row and row[0].strip().startswith("==="):
                    break
                continue

            mic_num = int(re.sub(r"[^\d]", "", row[0].strip()))
            all_mics.add(mic_num)
            actor = row[1].strip()
            default_char = row[2].strip()
            cells = row[3:]

            cell_map = {}
            for s_idx in range(num_scenes):
                val = cells[s_idx].strip() if s_idx < len(cells) else ""
                if val == "X":
                    cell_map[s_idx] = "ACTIVE"
                elif val == "-":
                    cell_map[s_idx] = "HELD"
                elif "[CHANGE]" in val:
                    cell_map[s_idx] = "CHANGE"

            if actor and actor not in ("—", "None", ""):
                raw_stints[mic_num].append({
                    "actor": actor,
                    "default_char": default_char,
                    "cells": cell_map
                })
    else:
        for row in reader[header_idx + 1:]:
            if not row or not row[0].strip().startswith("Mic "):
                if row and row[0].strip().startswith("==="):
                    break
                continue

            mic_num = int(re.sub(r"[^\d]", "", row[0].strip()))
            all_mics.add(mic_num)
            cells = row[2:]

            for s_idx in range(num_scenes):
                val = cells[s_idx].strip() if s_idx < len(cells) else "---"
                if val and val != "---":
                    clean = re.sub(r"\*+", "", val).strip()
                    clean = re.sub(r"^\[.*?\]\s*", "", clean).strip()
                    m = re.match(r"^(.*?)\s*\((.*?)\)$", clean)
                    actor = m.group(1).strip() if m else clean
                    char = m.group(2).strip() if m else ""
                    raw_stints[mic_num].append({
                        "actor": actor,
                        "default_char": char,
                        "cells": {s_idx: "ACTIVE"}
                    })

    max_mic = max(all_mics) if all_mics else 28
    mic_timeline = defaultdict(dict)

    for m in range(1, max_mic + 1):
        stints = raw_stints.get(m, [])
        if not stints:
            continue

        for stint_idx, stint in enumerate(stints):
            actor = stint["actor"]
            fallback_char = stint["default_char"].split(",")[0].strip()

            active_scenes = sorted([s for s, st in stint["cells"].items() if st == "ACTIVE"])
            if not active_scenes:
                continue

            first_active = active_scenes[0]
            last_active = active_scenes[-1]

            # Pre-fill from Scene 0 for the first actor on this pack so early scenes never say 'Idle'
            start_scene = 0 if stint_idx == 0 else first_active

            for s_idx in range(start_scene, last_active + 1):
                state = stint["cells"].get(s_idx, "HELD")
                if state == "CHANGE":
                    continue

                char_for_scene = None
                if scene_char_map:
                    if state == "ACTIVE":
                        char_for_scene = scene_char_map.get(s_idx, {}).get(actor)
                    if not char_for_scene:
                        future_active = [a_s for a_s in active_scenes if a_s >= s_idx]
                        target_s = future_active[0] if future_active else last_active
                        char_for_scene = scene_char_map.get(target_s, {}).get(actor)

                if not char_for_scene:
                    char_for_scene = fallback_char

                mic_timeline[m][s_idx] = {
                    "actor": actor,
                    "char": char_for_scene,
                    "state": state
                }

            for s_idx, st in stint["cells"].items():
                if st == "CHANGE" and s_idx not in mic_timeline[m]:
                    mic_timeline[m][s_idx] = {
                        "actor": actor,
                        "char": fallback_char,
                        "state": "CHANGE"
                    }

        # Keep last actor/character on the strip as HELD if no one else takes the pack later
        last_known = None
        for s_idx in range(num_scenes):
            if s_idx in mic_timeline[m] and mic_timeline[m][s_idx]["state"] in ("ACTIVE", "HELD"):
                last_known = mic_timeline[m][s_idx]
            elif s_idx not in mic_timeline[m] and last_known is not None:
                has_future_stint = any(
                    f_s in mic_timeline[m] and mic_timeline[m][f_s]["state"] == "ACTIVE"
                    for f_s in range(s_idx + 1, num_scenes)
                )
                if not has_future_stint:
                    mic_timeline[m][s_idx] = {
                        "actor": last_known["actor"],
                        "char": last_known["char"],
                        "state": "HELD"
                    }

    return scenes, mic_timeline, max_mic


def format_scribble_name(mic_num, actor, char, label_style="character", max_len=12):
    if not actor or actor in ("—", "None", "Spare"):
        return f"Mic {mic_num} Spare"[:max_len]

    parts = actor.split()
    first_name = parts[0]
    last_init = parts[-1][0] if len(parts) > 1 else ""

    if label_style == "character":
        text = char if char else f"{first_name} {last_init}".strip()
    elif label_style == "char_actor":
        short_char = char[:7].strip() if char else first_name
        text = f"{short_char}:{first_name[:4]}"
    elif label_style == "actor_full":
        text = actor
    else:  # "actor_first"
        text = f"{first_name} {last_init}".strip()

    return text[:max_len]


def build_layer_slots(mic_slice, bank_size=24):
    """
    Builds a 24-slot WING layer dictionary matching the full-size WING schema:
      Active slots: {"type": "CH", "i": <ch_num>, "dst": 1}
      Empty slots:  {"type": "OFF", "i": 0, "dst": 1}
    """
    slots = {}
    for slot_idx in range(1, bank_size + 1):
        if slot_idx <= len(mic_slice):
            ch_num = int(mic_slice[slot_idx - 1])
            slots[str(slot_idx)] = {
                "type": "CH",
                "i": ch_num,
                "dst": 1
            }
        else:
            slots[str(slot_idx)] = {
                "type": "OFF",
                "i": 0,
                "dst": 1
            }
    slots["ofs"] = 0
    return slots


def build_wing_snippet(ch_updates, active_mic_numbers, created_ts, bank_size=24):
    """
    Constructs a full-size Behringer WING .snip JSON dictionary:
      - ae_data.ch: Channel scribble strip names and colors
      - ce_data.layer.L["6"]: First 12 active mics on Left USER 1 (with "sel": 6)
      - ce_data.layer.C["5"]: Spillover mics (13..24) on Center USER 1 (with "sel": 5)
    """
    ch_dict = {}
    num_pars = 0

    for mic_num, data in sorted(ch_updates.items()):
        entry = {"name": data["name"]}
        num_pars += 1
        if "col" in data and data["col"] is not None:
            entry["col"] = data["col"]
            num_pars += 1
        ch_dict[str(mic_num)] = entry

    # Split active scene channels: first 12 go to Left (Layer 6), 13+ spill to Center (Layer 5)
    left_mics = active_mic_numbers[:12]
    center_spill_mics = active_mic_numbers[12:24]

    left_layer_6 = build_layer_slots(left_mics, bank_size=bank_size)
    center_layer_5 = build_layer_slots(center_spill_mics, bank_size=bank_size)

    # 3 params per slot (type, i, dst) * 24 slots + ofs + sel = 74 params per section
    num_pars += ((bank_size * 3) + 2) * 2

    return {
        "type": "snippet.10",
        "creator_fw": "VERSION_FULL",
        "creator_sn": "NO_SERIAL",
        "creator_model": "WING-EDIT",
        "creator_version": "3.3.3",
        "creator_name": "Wing-Edit",
        "created": created_ts,
        "active_show": "",
        "active_scene": "",
        "num_pars": num_pars,
        "ae_data": {
            "ch": ch_dict
        },
        "ce_data": {
            "layer": {
                "L": {
                    "6": left_layer_6,
                    "sel": 6
                },
                "C": {
                    "5": center_layer_5,
                    "sel": 5
                }
            }
        }
    }


def build_wing_show_file(show_name, generated_snips, created_ts, init_snap=None):
    """
    Builds a native Behringer WING / Wing-Edit 'showfile.1' JSON structure.
    """
    scenes_dict = {}
    cue_num = 1

    if init_snap:
        init_name = os.path.splitext(os.path.basename(init_snap))[0]
        scenes_dict[str(cue_num)] = {
            "name": init_name,
            "skip": False,
            "link": False,
            "type": "SNAP",
            "info": "Initial Console Snapshot",
            "tag": "",
            "midi_tx": "",
            "file": os.path.basename(init_snap)
        }
        cue_num += 1

    for snip in generated_snips:
        scenes_dict[str(cue_num)] = {
            "name": snip["name"],
            "skip": False,
            "link": False,
            "type": "SNIP",
            "info": f"{snip['scene_label']} ({len(snip['user1_mics'])} active on USR1)",
            "tag": "",
            "midi_tx": "",
            "file": snip["file"]
        }
        cue_num += 1

    ordered_scenes = {"count": cue_num - 1}
    ordered_scenes.update(scenes_dict)

    return {
        "type": "showfile.1",
        "creator_fw": "VERSION_FULL",
        "creator_sn": "NO_SERIAL",
        "creator_model": "WING-EDIT",
        "creator_version": "3.3.3",
        "creator_name": "Wing-Edit",
        "created": created_ts,
        "scenes": ordered_scenes
    }


def short_scene_slug(scene_label, idx):
    nums = re.findall(r"\d+", scene_label)
    if len(nums) >= 2:
        return f"{idx:02d}_A{nums[0]}_S{nums[1]}"
    return f"{idx:02d}_" + re.sub(r"[^A-Za-z0-9]+", "_", scene_label).strip("_")[:10]


def generate_wing_files(
    csv_path,
    json_path=None,
    output_dir="WING_SHOW",
    show_name="SHOW_LAVS",
    label_style="character",
    bank_size=24,
    init_snap=None
):
    scene_char_map = load_show_json_map(json_path) if json_path else None
    scenes, mic_timeline, num_mics = parse_tracking_csv(csv_path, scene_char_map)

    os.makedirs(output_dir, exist_ok=True)
    created_ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    COLOR_SOUNDCHECK = 6   # Cyan
    COLOR_ACTIVE     = 4   # Green
    COLOR_HELD       = 8   # Blue
    COLOR_SWAP_ALERT = 3   # Yellow
    COLOR_IDLE       = 1   # Dark

    generated_snips = []

    # 1. SOUNDCHECK SCENE (00_SOUNDCHECK.snip)
    sc_channels = {}
    sc_active_mics = []

    for m in range(1, num_mics + 1):
        first_cell = mic_timeline[m].get(0)
        if first_cell:
            first_actor = first_cell["actor"]
            first_char = first_cell["char"]
            name = format_scribble_name(m, first_actor, first_char, label_style)
            col = COLOR_SOUNDCHECK
            sc_active_mics.append(m)
        else:
            name = f"Mic {m} Spare"[:12]
            col = COLOR_IDLE

        sc_channels[m] = {"name": name, "col": col}

    sc_filename = "00_SOUNDCHECK.snip"
    sc_snip = build_wing_snippet(sc_channels, sc_active_mics, created_ts, bank_size=bank_size)
    with open(os.path.join(output_dir, sc_filename), "w", encoding="utf-8") as f:
        json.dump(sc_snip, f, indent=2)

    generated_snips.append({
        "index": 0,
        "name": "00_SOUNDCHECK",
        "file": sc_filename,
        "scene_label": "Pre-Show Sound Check",
        "user1_mics": sc_active_mics[:bank_size]
    })

    # 2. SHOW SCENES (01_A1_S1.snip ... N)
    prev_label_on_mic = {m: sc_channels[m]["name"] for m in range(1, num_mics + 1)}

    for s_idx, sc_label in enumerate(scenes):
        scene_num = s_idx + 1
        slug = short_scene_slug(sc_label, scene_num)
        snip_filename = f"{slug}.snip"

        ch_updates = {}
        present_in_scene_mics = []

        for m in range(1, num_mics + 1):
            cell = mic_timeline[m].get(s_idx)

            if cell is None:
                name = f"Mic {m} Spare"[:12]
                col = COLOR_IDLE
            elif cell["state"] == "CHANGE":
                next_actor, next_char = cell["actor"], cell["char"]
                for future_s in range(s_idx + 1, len(scenes)):
                    f_cell = mic_timeline[m].get(future_s)
                    if f_cell and f_cell["state"] in ("ACTIVE", "HELD"):
                        next_actor, next_char = f_cell["actor"], f_cell["char"]
                        break
                upcoming = format_scribble_name(m, next_actor, next_char, label_style, max_len=11)
                name = f"*{upcoming}"
                col = COLOR_SWAP_ALERT
            else:
                actor = cell["actor"]
                char = cell["char"]
                state = cell["state"]
                name = format_scribble_name(m, actor, char, label_style)

                if state == "ACTIVE":
                    present_in_scene_mics.append(m)
                    col = COLOR_SWAP_ALERT if prev_label_on_mic.get(m) != name else COLOR_ACTIVE
                else:
                    col = COLOR_HELD

            ch_updates[m] = {"name": name, "col": col}
            prev_label_on_mic[m] = name

        snip_data = build_wing_snippet(
            ch_updates,
            present_in_scene_mics,
            created_ts,
            bank_size=bank_size
        )
        with open(os.path.join(output_dir, snip_filename), "w", encoding="utf-8") as f:
            json.dump(snip_data, f, indent=2)

        generated_snips.append({
            "index": scene_num,
            "name": slug,
            "file": snip_filename,
            "scene_label": sc_label,
            "user1_mics": present_in_scene_mics
        })

    # 3. MASTER SHOW FILE (.show)
    show_data = build_wing_show_file(show_name, generated_snips, created_ts, init_snap=init_snap)
    show_filepath = os.path.join(output_dir, f"{show_name}.show")
    with open(show_filepath, "w", encoding="utf-8") as f:
        json.dump(show_data, f, indent=2)

    print(f"Generated {len(generated_snips)} Snippets + '{show_name}.show' ({show_data['scenes']['count']} scenes) in ./{output_dir}/")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Convert Lav Tracking CSV + show_data.json to Behringer WING Show.")
    parser.add_argument("csv_file", nargs="?", default="mic_tracking_sheet.csv", help="Path to mic_tracking_sheet.csv")
    parser.add_argument("json_file", nargs="?", default="show_data.json", help="Path to show_data.json for per-scene character names")
    parser.add_argument("--outdir", default="WING_SHOW", help="Output folder name")
    parser.add_argument("--show-name", default="SHOW_LAVS", help="Show name on console")
    parser.add_argument(
        "--style",
        choices=["character", "char_actor", "actor_first", "actor_full"],
        default="character",
        help="Scribble strip format (default: 'character')"
    )
    parser.add_argument("--bank-size", type=int, default=24, help="User Bank 1 size (default: 24)")
    parser.add_argument(
        "--init-snap",
        default=None,
        help="Optional filename of a base console snapshot (e.g. 'init.snap') to place at Scene 1"
    )
    args = parser.parse_args()
    generate_wing_files(
        args.csv_file,
        args.json_file,
        args.outdir,
        args.show_name,
        args.style,
        args.bank_size,
        args.init_snap
    )